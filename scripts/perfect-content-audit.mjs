// 4. 전체 35개 기사 전수 정밀 정규화 (비교표 H2 -> H3 치환, 소제목 줄바꿈 깨짐 복원, 가독성 문단 쪼개기)
const allRows = db.prepare("SELECT id, title, category, content FROM articles").all();
let normalizedCount = 0;
const updateContentStmt = db.prepare("UPDATE articles SET content = ? WHERE id = ?");

for (const r of allRows) {
  let c = r.content;

  // A. 비교표나 테이블 캡션이 H2(##)로 되어 블루바가 생기던 문제를 H3(###)로 다운그레이드
  c = c.replace(/^##\s+([^\n]*(?:비교표|비교\s*표|체크포인트|안내\s*창구|유의\s*사항|포인트|가이드|목록|현황|일정\b)[^\n]*)/gm, "### $1");
  c = c.replace(/^##\s+주요\s*핵심\s*비교표/gm, "### 주요 핵심 비교표");
  c = c.replace(/^##\s+원유\s*수급\s*및\s*의존도\s*비교표/gm, "### 원유 수급 및 의존도 비교표");
  c = c.replace(/^##\s+설비\s*교체\s*지원\s*및\s*연계\s*혜택/gm, "### 설비 교체 지원 및 연계 혜택");
  c = c.replace(/^##\s+인사\s*정국\s*대응\s*시나리오별\s*쟁점\s*비교표/gm, "### 인사 정국 대응 시나리오별 쟁점 비교표");

  // B. 잘린 소제목 한 줄로 온전히 병합
  c = c.replace(/^##\s+1\.\s*주요\s*동향\s*\n+\s*및\s*배경/gm, "## 1. 주요 동향 및 배경");
  c = c.replace(/^##\s+1\.\s*주요\s*동향\s*$/gm, "## 1. 주요 동향 및 배경");
  c = c.replace(/^##\s+2\.\s*기술·시장적\s*파급\s*\n+\s*효과/gm, "## 2. 기술·시장적 파급 효과");
  c = c.replace(/^##\s+2\.\s*주요\s*쟁점\s*\n+\s*및\s*파장/gm, "## 2. 주요 쟁점 및 파장");
  c = c.replace(/^##\s+2\.\s*주요\s*쟁점\s*$/gm, "## 2. 주요 쟁점 및 파장");
  c = c.replace(/^##\s+3\.\s*세부\s*혜택\s*$/gm, "## 3. 세부 혜택 및 수치 비교");
  c = c.replace(/^##\s+3\.\s*세부\s*혜택\s*\n+\s*및\s*수치\s*비교/gm, "## 3. 세부 혜택 및 수치 비교");
  c = c.replace(/^##\s+3\.\s*각계\s*반응\s*및\s*주요\s*쟁점\s*\n+\s*비교/gm, "## 3. 각계 반응 및 주요 쟁점 비교");
  c = c.replace(/^##\s+3\.\s*각계\s*반응\s*및\s*주요\s*쟁점\s*$/gm, "## 3. 각계 반응 및 주요 쟁점 비교");
  c = c.replace(/^##\s+3\.\s*핵심\s*지표\s*및\s*수치\s*\n+\s*비교/gm, "## 3. 핵심 지표 및 수치 비교");
  c = c.replace(/^##\s+3\.\s*핵심\s*지표\s*및\s*스펙\s*\n+\s*비교/gm, "## 3. 핵심 지표 및 스펙 비교");
  c = c.replace(/^##\s+4\.\s*신청\s*방법\s*$/gm, "## 4. 신청 방법 및 향후 일정");
  c = c.replace(/^##\s+4\.\s*신청\s*방법\s*\n+\s*및\s*향후\s*일정/gm, "## 4. 신청 방법 및 향후 일정");
  c = c.replace(/^##\s+4\.\s*향후\s*전망\s*및\s*관전\s*포인트/gm, "## 4. 향후 전망 및 관전 포인트");
  c = c.replace(/^##\s+4\.\s*향후\s*전망\s*\n+\s*및\s*관전\s*포인트/gm, "## 4. 향후 전망 및 관전 포인트");
  c = c.replace(/^##\s+4\.\s*향후\s*전망\s*\n+\s*및\s*시사점/gm, "## 4. 향후 전망 및 시사점");
  c = c.replace(/^##\s+4\.\s*향후\s*전망\s*\n+\s*및\s*투자자\s*유의점/gm, "## 4. 향후 전망 및 투자자 유의점");

  // C. 단독 '#' 등 잔여 기호 완전히 제거
  c = c.replace(/^[ \t]*#[ \t]*$/gm, "");

  // D. 소제목 앞뒤 여백 정돈 (H2 앞 2줄, 뒤 1줄)
  c = c.replace(/([^\n])\s*\n##\s+/g, "$1\n\n## ");
  c = c.replace(/^(##\s+[^\n]+)\n+(?!\n)/gm, "$1\n\n");
  c = c.replace(/^(###\s+[^\n]+)\n+(?!\n)/gm, "$1\n\n");

  // E. 연속 3개 이상의 개행을 2개로 압축
  c = c.replace(/\n{3,}/g, "\n\n").trim();

  updateContentStmt.run(c, r.id);
  normalizedCount++;
}

